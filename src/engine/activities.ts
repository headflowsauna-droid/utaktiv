/**
 * Søker og filtrerer aktiviteter etter brukerens by, interesser og barnas alder
 */
export function filterActivitiesForCity(
  activities: ActivityItem[],
  city: string
): ActivityItem[] {
  const normCity = city.trim().toLowerCase();
  return activities.filter(a => a.city.toLowerCase() === normCity);
}

export interface TrailInfo {
  type: 'mountain_hike' | 'cross_country_ski' | 'forest_trail' | 'coastal';
  difficulty: 'green' | 'blue' | 'red' | 'black'; // DNT-standard: Enkel (grønn), Middels (blå), Krevende (rød), Ekspert (svart)
  distanceKm: number;
  elevationMeters: number;
  surface?: string;
  trailMarking: string; // f.eks. 'DNT rødmerket T-sti', 'Preparert trikkespor', 'Lysløype'
  isGroomedSkiTrack?: boolean;
}

export interface ActivityAddOn {
  id: string;
  title: string;
  type: 'cafe' | 'sauna' | 'restaurant' | 'viewpoint' | 'gear';
  partnerName: string;
  description: string;
  priceNok: number;
  commissionNok: number; // Utaktivs formidlingshonorar per salg
  durationMinutes: number;
  badgeEmoji: string;
  bookingUrl?: string;
  directSaleAvailable?: boolean;
}

export interface AccommodationProximity {
  sunOrMountainTrail: string; // f.eks. "50m rett til stistart Ulriken"
  concertVenue?: string; // f.eks. "18 min med buss/bybane til Koengen"
  cityCenter: string; // f.eks. "12 min med buss til Torgallmenningen"
}

export interface AccommodationInfo {
  type: 'hostel' | 'hotel' | 'dnt_cabin' | 'guesthouse';
  priceLevel: 'budget' | 'moderate' | 'comfort';
  pricePerNightNok: number;
  amenities: string[]; // f.eks. ['Frokostbuffé inkludert', 'Gjestekjøkken', 'Tørkerom', 'Bagasjeoppbevaring']
  proximity: AccommodationProximity;
  checkInTime?: string;
  checkOutTime?: string;
  bookingUrl?: string;
}

export interface SeniorSafetyInfo {
  surface: 'paved' | 'firm_gravel' | 'trail_roots' | 'rough_rock';
  benchDensity: 'frequent' | 'occasional' | 'none';
  hasPublicRestroom: boolean;
  restroomDistanceMeters?: number;
  parkingDistanceMeters: number;
  shelteredSunCorner: boolean;
}

export interface TouristSecurityInfo {
  requiredFootwear: 'sneakers_fine' | 'hiking_shoes' | 'sturdy_mountain_boots';
  drivingTimeWarning?: string;
  drivingTimeWarningEn?: string;
  latestSafeStartHour?: string;
  latestSafeStartHourEn?: string;
  microclimateTip?: string;
  microclimateTipEn?: string;
}

export type ActivityCategory =
  | 'concert'
  | 'show'
  | 'family'
  | 'nature'
  | 'cafebar'
  | 'festival'
  | 'sports'
  | 'hike'
  | 'ski'
  | 'accommodation'
  | 'hostel';

export interface ActivityItem {
  id: string;
  title: string;
  titleEn?: string;
  category: ActivityCategory;
  description: string;
  descriptionEn?: string;
  locationName: string;
  locationNameEn?: string;
  city: string;
  coordinates: {
    lat: number;
    lng: number;
  };
  isOutdoor: boolean;
  date?: string; // YYYY-MM-DD
  time?: string; // HH:mm
  durationMinutes: number;
  targetAgeMin?: number;
  targetAgeMax?: number;
  strollerAccessible: boolean;
  tripAdvisorRating?: number;
  reviewCount?: number;
  sourceUrl: string;
  imageUrl?: string;
  artists?: string[];
  estimatedLux: number; // Forventet dagslys i luks
  sunFacing?: 'south' | 'west' | 'open' | 'shaded'; // For uteservering og solfangst
  ticket?: TicketConfig;
  trail?: TrailInfo;
  accommodation?: AccommodationInfo;
  seniorSafety?: SeniorSafetyInfo;
  touristSecurity?: TouristSecurityInfo;
  addOns?: ActivityAddOn[]; // Gjør det til en hel dag (bolle på kafe, Heit badstue, etc.)
  checkinTarget?: {
    badgeName: string;
    solarBonusLux: number;
    radiusMeters: number;
  };
  /** Gratis tur, søndagsbesøk eller billett som kjøpes hos stedet. Aldri vår betalingsknapp. */
  stopKind?: 'free' | 'sunday-dropin' | 'ticket-on-site';
  /** Nøkkel i horisont-tabellen. Klokken regnes, den lagres ikke. */
  sunPointId?: string;
  /** Retning utsikten vender, grader fra nord. Geografi, ikke et solur. */
  viewAzimuthDeg?: number;
  viewLabel?: string;
}

